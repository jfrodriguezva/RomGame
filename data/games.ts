export type GameStatus = "ready" | "soon";

export interface GameDef {
  id: string;
  slug: string;
  title: string;
  emoji: string;
  /** Qué hace el niño, dicho en sus palabras. */
  description: string;
  area: Area;
  /** Edad orientativa, no una regla. */
  edad: [number, number];
  /** Material Montessori que inspira la actividad. */
  material: string;
  /** Qué desarrolla. Se muestra en la vista de mamá y papá. */
  objetivo: string;
  status: GameStatus;
  /** Actividad libre: sin niveles, sin puntaje, sin final. */
  libre?: boolean;
  /** Ruta propia cuando no vive bajo /games. */
  href?: string;
  /** Novedad de esta versión. */
  nuevo?: boolean;
}

function g(def: Omit<GameDef, "status"> & { status?: GameStatus }): GameDef {
  return { status: "ready", ...def };
}

