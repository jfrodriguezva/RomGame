export function getGame(slug: string): GameDef | undefined {
  return games.find((game) => game.slug === slug);
}

export function gamesByArea(area: Area): GameDef[] {
  return games.filter((game) => game.area === area);
}

export function rutaDeJuego(game: GameDef): string {
  return game.href ?? `/games/${game.slug}`;
}

